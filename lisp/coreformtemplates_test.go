package lisp_test

import (
	"flag"
	"go/format"
	"os"
	"strconv"
	"strings"
	"testing"

	"github.com/luthersystems/elps/lisp"
	"github.com/luthersystems/elps/parser"
	"github.com/stretchr/testify/assert"
	"github.com/stretchr/testify/require"
)

var updateCoreFormTemplates = flag.Bool("update-core-form-templates", false, "rewrite coreformtemplates_gen.go")

// TestCoreFormTemplatesGenerated reads each core form template's source with
// the elps reader and checks that coreformtemplates_gen.go holds it
// compiled.  Package lisp cannot import the reader, so the compiled
// templates are checked in; run go generate ./lisp after changing one.
func TestCoreFormTemplatesGenerated(t *testing.T) {
	srcs, params := lisp.CoreFormSources()
	require.NotEmpty(t, srcs)
	var b strings.Builder
	b.WriteString("// Code generated by TestCoreFormTemplatesGenerated; DO NOT EDIT.\n\npackage lisp\n\n")
	b.WriteString("var coreFormTemplates = map[string]*FormTemplate{\n")
	seen := map[string]bool{}
	for i, src := range srcs {
		key := lisp.CoreFormKey(src, params[i])
		if seen[key] {
			continue
		}
		seen[key] = true
		forms, err := parser.NewReader().Read("template", strings.NewReader(src))
		require.NoError(t, err, src)
		require.Len(t, forms, 1, src)
		tmpl, err := lisp.NewFormTemplate(forms[0], params[i]...)
		require.NoError(t, err, src)
		b.WriteString("\t" + goQuote(key) + ": " + lisp.FormTemplateGoLiteral(tmpl) + ",\n")
	}
	b.WriteString("}\n")
	want, err := format.Source([]byte(b.String()))
	require.NoError(t, err)
	const path = "coreformtemplates_gen.go"
	if *updateCoreFormTemplates {
		require.NoError(t, os.WriteFile(path, want, 0o600))
		return
	}
	got, err := os.ReadFile(path)
	require.NoError(t, err)
	assert.Equal(t, string(want), string(got), "coreformtemplates_gen.go is out of date; run go generate ./lisp")
}

// goQuote writes s as a Go raw string when it can, so the generated keys
// read as the templates' source.
func goQuote(s string) string {
	if !strings.Contains(s, "`") {
		return "`" + s + "`"
	}
	return strconv.Quote(s)
}
